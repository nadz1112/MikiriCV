/** Normalizes Vietnamese text (diacritics + đ/Đ) for consistent client-side offline search. */
export function normalizeForSearchClient(input: string): string {
  return input
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}
